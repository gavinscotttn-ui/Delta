#!/usr/bin/env node
/*
 * Builds the files Astra loads for the document library.
 *
 *   library/manifest.json  (you maintain)  +  library/**.pdf  ->  js/library/docs.js, js/library/index.js
 *
 * docs.js   : the document list (title, category, file, pages, size, summary).
 * index.js  : the text of every page, so documents can be searched and opened at the right page.
 *
 * Needs poppler's `pdftotext` and `pdfinfo` on the PATH. Run with: npm run library
 */
import { readFileSync, writeFileSync, statSync, existsSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const libDir = join(root, "library");
const outDir = join(root, "js", "library");
const manifest = JSON.parse(readFileSync(join(libDir, "manifest.json"), "utf8"));

function run(cmd, args) {
  const r = spawnSync(cmd, args, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
  if (r.error)
    throw new Error(`${cmd} is required but could not be run (${r.error.message}). Install poppler-utils.`);
  return r.stdout;
}

/* Tidy one page of extracted text for searching. */
function cleanPage(text) {
  const lines = text
    .split("\n")
    .map((l) => l.replace(/\s+/g, " ").trim())
    .filter(Boolean);
  const dotted = lines.filter((l) => /\.{5,}/.test(l)).length;
  if (lines.length && dotted / lines.length > 0.4) return ""; /* contents page */
  return lines
    .filter((l) => !/\.{5,}/.test(l))
    .join(" ")
    .replace(/\s{2,}/g, " ")
    .trim();
}

const docs = [];
const index = [];
const problems = [];

manifest.documents.forEach((d, docIndex) => {
  const file = join(libDir, d.file);
  if (!existsSync(file)) {
    problems.push(`${d.id}: missing file ${d.file}`);
    return;
  }
  if (d.original && !existsSync(join(libDir, d.original)))
    problems.push(`${d.id}: missing original ${d.original}`);

  const info = run("pdfinfo", [file]);
  const pages = Number((info.match(/^Pages:\s+(\d+)/m) || [])[1]) || 0;

  let pageTexts;
  if (d.transcript) {
    pageTexts = readFileSync(join(root, "tools", "transcripts", d.transcript), "utf8").split("\f");
    if (pageTexts.length > pages) pageTexts.length = pages;
  } else {
    pageTexts = run("pdftotext", [file, "-"]).split("\f");
  }

  let chars = 0;
  if (!d.noIndex) {
    pageTexts.forEach((t, i) => {
      const text = cleanPage(t);
      if (text.length >= 20) {
        index.push([docIndex, i + 1, text]);
        chars += text.length;
      }
    });
    if (chars < 60 && d.kind !== "Empty")
      problems.push(`${d.id}: very little searchable text (${chars} chars). Add a transcript.`);
  }

  docs.push({
    id: d.id,
    title: d.title,
    category: d.category,
    kind: d.kind || "Guide",
    file: "library/" + d.file,
    original: d.original ? "library/" + d.original : "",
    pages,
    bytes: statSync(file).size,
    originalBytes: d.original ? statSync(join(libDir, d.original)).size : 0,
    summary: d.summary || "",
    tags: d.tags || [],
    note: d.note || "",
    indexed: !d.noIndex,
  });
});

if (problems.length) {
  console.error("Problems:\n  " + problems.join("\n  "));
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
const stamp = "/* Generated by tools/build-library.mjs. Do not edit by hand. */\n";
writeFileSync(
  join(outDir, "docs.js"),
  stamp +
    "window.AstraLibrary = " +
    JSON.stringify({ categories: manifest.categories, docs }, null, 1) +
    ";\n",
);
/* docs.js lists documents; index.js is the page text. The index refers to documents by position in the list. */
const positions = new Map(manifest.documents.map((d, i) => [i, docs.findIndex((x) => x.id === d.id)]));
const body = index.map(([docIndex, page, text]) => [positions.get(docIndex), page, text]);
writeFileSync(
  join(outDir, "index.js"),
  stamp + "window.AstraLibrary.index = " + JSON.stringify(body) + ";\n",
);

const kb = (n) => (n / 1024).toFixed(0) + " KB";
console.log(`${docs.length} documents, ${body.length} searchable pages.`);
console.log(
  `docs.js ${kb(statSync(join(outDir, "docs.js")).size)}, index.js ${kb(statSync(join(outDir, "index.js")).size)}`,
);
