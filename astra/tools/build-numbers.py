#!/usr/bin/env python3
"""Builds js/uk-numbers.js: UK number types, formats, areas and original mobile networks.

The data comes from Google's libphonenumber (Apache-2.0), as shipped in the Python `phonenumbers` package.
Its files are read as text and parsed with ast.literal_eval: nothing from the package is imported or run.

    pip download --no-deps phonenumbers      # one-off, on a computer with internet
    unzip phonenumbers-*.whl -d /tmp/pn
    python3 -I tools/build-numbers.py /tmp/pn
"""
import ast
import glob
import json
import os
import re
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
root = sys.argv[1]
pkg = os.path.join(root, "phonenumbers")
meta = next(iter(glob.glob(os.path.join(root, "phonenumbers-*.dist-info"))), "")
version = re.search(r"phonenumbers-([\d.]+)\.dist-info", meta).group(1) if meta else "unknown"


def prefixes(folder):
    """'44141': {'en': 'Glasgow'} entries for the UK, from geodata or carrierdata."""
    out = {}
    for path in sorted(glob.glob(os.path.join(pkg, folder, "data*.py"))):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if not line.startswith("'44"):
                continue
            m = re.match(
                r"^'(44\d+)':\s*\{'en':\s*(?:u\()?('(?:[^'\\]|\\.)*'|\"(?:[^\"\\]|\\.)*\")\)?\s*(?:,\s*'[a-z]{2}':.*)?\},?$",
                line,
            )
            if not m:
                sys.exit(f"Unexpected line in {path}: {line[:120]}")
            out[m.group(1)[2:]] = ast.literal_eval(m.group(2))
    return out


region = open(os.path.join(pkg, "data", "region_GB.py"), encoding="utf-8").read()


def number_types(text):
    out = {}
    for name, pattern in re.findall(r"(\w+)=PhoneNumberDesc\(national_number_pattern=('(?:[^'\\]|\\.)*')", text):
        if name != "general_desc":
            out[name] = ast.literal_eval(pattern)
    return out


types = number_types(region)
# The Crown Dependencies share +44 but are separate regions in libphonenumber.
crown = {}
for code, place in (("IM", "Isle of Man"), ("JE", "Jersey"), ("GG", "Guernsey")):
    text = open(os.path.join(pkg, "data", f"region_{code}.py"), encoding="utf-8").read()
    crown[place] = number_types(text)

formats = []
for pattern, fmt, leading in re.findall(
    r"NumberFormat\(pattern=('(?:[^'\\]|\\.)*'), format=('(?:[^'\\]|\\.)*'), leading_digits_pattern=(\[(?:'(?:[^'\\]|\\.)*'(?:,\s*)?)*\])",
    region,
):
    lead = ast.literal_eval(leading)
    formats.append(
        {"pattern": ast.literal_eval(pattern), "format": ast.literal_eval(fmt), "leading": lead[-1] if lead else ""}
    )

general = re.search(r"general_desc=PhoneNumberDesc\(national_number_pattern=('(?:[^'\\]|\\.)*')", region)

data = {
    "source": f"libphonenumber via phonenumbers {version} (Apache-2.0)",
    "general": ast.literal_eval(general.group(1)),
    "types": types,
    "crown": crown,
    "formats": formats,
    "areas": prefixes("geodata"),
    "networks": prefixes("carrierdata"),
}
if not data["areas"] or not data["networks"] or "mobile" not in types or not formats:
    sys.exit("The package did not contain the expected UK data.")

target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "uk-numbers.js")
with open(target, "w", encoding="utf-8") as f:
    f.write(
        "/* Generated by tools/build-numbers.py from Google's libphonenumber (Apache-2.0,\n"
        "   https://github.com/google/libphonenumber). Do not edit by hand. */\n"
        "window.AstraNumberData = "
        + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
print(
    f"{len(data['areas'])} areas, {len(data['networks'])} mobile ranges, {len(types)} number types, "
    f"{len(formats)} formats from {data['source']}"
)
