#!/usr/bin/env node
/*
 * Records the fingerprint of every past version of every built-in template, quick line, workflow, guide and shortcut,
 * read from git history, into js/seed/history.js.
 *
 * Astra uses it to update built-in items people have not edited: if a stored item matches a past built-in version,
 * nobody changed it, so it can safely take the latest wording. Run this before committing a change to js/seed/:
 *
 *   npm run seeds
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const KINDS = ["templates", "snippets", "workflows", "knowledge", "shortcuts"];
const git = (...args) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const fingerprintSource = readFileSync(join(root, "js", "seed-fingerprint.js"), "utf8");

/* The seed files a commit loads, in the order its index.html loads them. */
function seedScripts(commit) {
  let html = "";
  try {
    html = git("show", `${commit}:index.html`);
  } catch {
    return [];
  }
  return [...html.matchAll(/<script src="(js\/seed\/[^"]+)"/g)]
    .map((m) => m[1])
    .filter((f) => !f.endsWith("history.js"));
}

function fingerprintsAt(commit) {
  const files = seedScripts(commit);
  if (!files.length) return {};
  const sandbox = { structuredClone, URL };
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(fingerprintSource, sandbox);
  for (const f of files) {
    let src;
    try {
      src = git("show", `${commit}:${f}`);
    } catch {
      continue;
    }
    vm.runInContext(src, sandbox, { filename: `${commit}:${f}` });
  }
  const seed = sandbox.AstraSeed || {};
  const out = {};
  for (const kind of KINDS)
    for (const item of seed[kind] || []) out[`${kind}:${item.id}`] = sandbox.AstraFingerprint.of(kind, item);
  return out;
}

export function collect() {
  const commits = git("log", "--format=%H", "--", "js/seed", "index.html").trim().split("\n").filter(Boolean);
  const history = {};
  for (const c of commits) {
    for (const [key, fp] of Object.entries(fingerprintsAt(c))) {
      (history[key] ||= new Set()).add(fp);
    }
  }
  return Object.fromEntries(
    Object.keys(history)
      .sort()
      .map((k) => [k, [...history[k]].sort()]),
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const history = collect();
  const body =
    "/* Generated by tools/seed-history.mjs (npm run seeds). Do not edit by hand.\n" +
    "   Fingerprints of past versions of each built-in item, so unedited copies can be updated to the latest wording. */\n" +
    "window.AstraSeed.history = " +
    JSON.stringify(history, null, 1) +
    ";\n";
  writeFileSync(join(root, "js", "seed", "history.js"), body);
  console.log(
    `${Object.keys(history).length} built-in items, ${Object.values(history).flat().length} past versions.`,
  );
}
