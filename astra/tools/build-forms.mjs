#!/usr/bin/env node
/* Bundles the blank LOA (library/company/Customer Letter of Authority (LOA).docx) into js/forms/loa-template.js,
   so the LOA filler can build a filled-in copy in the browser. Run after replacing the LOA: npm run forms */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "library", "company", "Customer Letter of Authority (LOA).docx");
const b64 = readFileSync(source).toString("base64");
writeFileSync(
  join(root, "js", "forms", "loa-template.js"),
  "/* Generated by tools/build-forms.mjs from library/company/Customer Letter of Authority (LOA).docx. Do not edit. */\n" +
    "window.AstraForms = window.AstraForms || {};\n" +
    `window.AstraForms.loaDocx = "${b64}";\n`,
);
console.log(`LOA template bundled (${Math.round(b64.length / 1024)} KB).`);
